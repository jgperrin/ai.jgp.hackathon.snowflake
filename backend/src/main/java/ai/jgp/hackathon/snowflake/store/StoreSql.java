package ai.jgp.hackathon.snowflake.store;

import ai.jgp.hackathon.snowflake.catalog.Identifiers;

/** DDL and DML for the artifacts table. Creates, inserts and reads; never updates or deletes. */
final class StoreSql {

    static final String SCHEMA = "DATA_PRODUCTS";
    static final String TABLE = "ARTIFACTS";

    private StoreSql() {
    }

    static String schema(String database) {
        return Identifiers.quote(database, "database") + "." + Identifiers.quote(SCHEMA, "schema");
    }

    static String table(String database) {
        return schema(database) + "." + Identifiers.quote(TABLE, "table");
    }

    static String createSchema(String database) {
        return "CREATE SCHEMA IF NOT EXISTS " + schema(database)
                + " COMMENT = 'ODCS contracts, ODPS products and OSI/Apache Ossie models generated by DIND'";
    }

    static String createTable(String database) {
        return "CREATE TABLE IF NOT EXISTS " + table(database) + " ("
                + "SAVE_ID STRING NOT NULL, PRODUCT_ID STRING NOT NULL, ARTIFACT_ID STRING NOT NULL, "
                + "KIND STRING NOT NULL, NAME STRING, VERSION STRING, STATUS STRING, "
                + "YAML STRING, DOC VARIANT, "
                + "SAVED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(), "
                + "SAVED_BY STRING DEFAULT CURRENT_USER())";
    }

    /** VARIANT values can only be computed in a SELECT, hence INSERT ... SELECT PARSE_JSON(?). */
    static String insert(String database) {
        return "INSERT INTO " + table(database)
                + " (SAVE_ID, PRODUCT_ID, ARTIFACT_ID, KIND, NAME, VERSION, STATUS, YAML, DOC, SAVED_AT)"
                + " SELECT ?, ?, ?, ?, ?, ?, ?, ?, PARSE_JSON(?), ?::TIMESTAMP_TZ";
    }

    static String latest(String database) {
        return "SELECT SAVE_ID, NAME, VERSION, TO_VARCHAR(SAVED_AT, 'YYYY-MM-DD\"T\"HH24:MI:SSTZH:TZM') AS SAVED_AT FROM "
                + table(database) + " WHERE KIND = 'ODPS'"
                + " QUALIFY ROW_NUMBER() OVER (PARTITION BY PRODUCT_ID ORDER BY SAVED_AT DESC) = 1"
                + " ORDER BY SAVED_AT DESC LIMIT 100";
    }

    static String load(String database) {
        return "SELECT ARTIFACT_ID, KIND, NAME, VERSION, STATUS, YAML, TO_JSON(DOC) AS DOC FROM " + table(database)
                + " WHERE SAVE_ID = ? ORDER BY CASE KIND WHEN 'ODPS' THEN 0 WHEN 'ODCS' THEN 1 ELSE 2 END, ARTIFACT_ID";
    }
}
